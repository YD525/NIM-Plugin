using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;

namespace NIM_Plugin.Data
{
    public sealed class Mod_File
    {
        public string Path { get; }

        private readonly Func<byte[]> _Read;
        private readonly Func<byte[], bool> _Save;
        private readonly Func<int> _GetFileUniqueKey;

        public Mod_File(string Path, Func<byte[]> Read, Func<byte[], bool> Save, Func<int> GetFileUniqueKey)
        {
            this.Path = Path;

            _Read = Read;
            _Save = Save;
            _GetFileUniqueKey = GetFileUniqueKey;
        }

        public byte[] Read()
        {
            return _Read();
        }

        public int GetFileUniqueKey()
        {
            return _GetFileUniqueKey();
        }

        public bool Save(byte[] Data)
        {
            return _Save(Data);
        }
    }

    public class Mod_Data
    {
        public string Key = "";
        public string Data = "";

        public int GroupID = 0;

        public Mod_Data(string Key, string Data,int GroupID = 0)
        { 
            this.Key = Key;
            this.Data = Data;
            this.GroupID = GroupID;
        }
    }

    public class Mod_Content
    {
        public string ModName = "";

        private List<Mod_Data> _Rows = new List<Mod_Data>() { };
        public ReadOnlyCollection<Mod_Data> Rows
        {
            get { return _Rows.AsReadOnly(); }
        }

        public HashSet<string> UniqueKeys = new HashSet<string>();

        public void Clear()
        {
            _Rows.Clear();
        }
        public void Add(string Key,string Value,int GroupID = 0)
        {
            if (UniqueKeys.Contains(Key))
            {
                throw new Exception("The primary key must be malicious.");
            }

            UniqueKeys.Add(Key);

            _Rows.Add(new Mod_Data(Key,Value,GroupID));
        }
    }

    public interface I_ModReader
    {
        /// <summary>
        /// Gets or sets the file extensions that this plugin is responsible for.
        /// Multiple extensions can be separated by commas, e.g. ".json,.xml,.txt".
        /// </summary>
        string TakenOverFileExtension { get; set; }

        /// <summary>
        /// Gets or sets the names of the subdirectories under the mod root directory
        /// whose files this plugin is responsible for.
        /// For example, "xxx" and "yyy".
        /// Leave empty to use the default mod directory structure.
        /// </summary>
        List<string> TakenOverDirectoryNames { get; set; }

        /// <summary>
        /// Gets or sets whether this plugin takes over the entire mod directory
        /// and is responsible for handling all supported files within it.
        /// </summary>
        bool CanTakeOverEntireDirectory { get; set; }

        /// <summary>
        /// Receives the file list provided by the host application and parses
        /// the files that this plugin can handle.
        ///
        /// Each Mod_File provides access to the corresponding file through
        /// methods such as Read(), GetFileUniqueKey(), and Save().
        /// The plugin can decide when to read each file.
        /// </summary>
        /// <param name="ModFiles">
        /// The list of files provided by the host application.
        /// </param>
        /// <returns>
        /// The parsed mod content generated by this plugin.
        /// </returns>
        Mod_Content Read(List<Mod_File> ModFiles);

        /// <summary>
        /// Determines whether this plugin successfully recognized and can handle
        /// the provided mod files.
        /// 
        /// This method is called after Read().
        /// If it returns false, the host application can pass the files
        /// to the next available reader plugin.
        /// </summary>
        /// <returns>
        /// True if this plugin can handle the provided files; otherwise, false.
        /// </returns>
        bool CanRead();

        /// <summary>
        /// Saves the translated mod content back to the original files.
        /// 
        /// The plugin is responsible for mapping translated content back to
        /// its original data structures and serializing it as needed.
        /// Actual file I/O is performed through the Save() method provided
        /// by the corresponding Mod_File instance.
        /// </summary>
        /// <param name="Content">
        /// The translated mod content to save.
        /// </param>
        /// <returns>
        /// The number of successful save operations.
        /// </returns>
        int Save(Mod_Content Content);
    }
}
